"use client";

import { useState } from "react";
import { Sparkles } from "lucide-react";
import { Button } from "@/components/ui/button";
import { Card, CardContent, CardHeader, CardTitle, CardDescription } from "@/components/ui/card";
import type { Holding } from "@/lib/agents/investment/types";

export function AIInsightsPanel({
  holdings,
  initialInsight,
}: {
  holdings: Holding[];
  initialInsight: { content: string; createdAt: string } | null;
}) {
  const [insight, setInsight] = useState(initialInsight);
  const [loading, setLoading] = useState(false);
  const [error, setError] = useState<string | null>(null);

  async function handleGenerate() {
    setLoading(true);
    setError(null);

    const res = await fetch("/api/agents/investment/insights", {
      method: "POST",
    });

    setLoading(false);

    if (!res.ok) {
      const body = await res.json().catch(() => null);
      setError(body?.error ?? "Something went wrong generating insights.");
      return;
    }

    setInsight(await res.json());
  }

  return (
    <Card>
      <CardHeader>
        <div className="flex items-start justify-between gap-4">
          <div>
            <CardTitle>AI insights</CardTitle>
            <CardDescription>
              Diversification and concentration notes, generated by Claude.
            </CardDescription>
          </div>
          <Button
            size="sm"
            variant="outline"
            onClick={handleGenerate}
            disabled={loading || holdings.length === 0}
          >
            <Sparkles className="h-4 w-4" />
            {loading ? "Generating..." : "Generate insights"}
          </Button>
        </div>
      </CardHeader>
      <CardContent>
        {error && <p className="mb-3 text-sm text-red-600">{error}</p>}

        {insight ? (
          <div className="space-y-3">
            <div className="whitespace-pre-wrap text-sm leading-relaxed text-neutral-700 dark:text-neutral-300">
              {insight.content}
            </div>
            <p className="text-xs text-neutral-400">
              Generated {new Date(insight.createdAt).toLocaleString()} ·
              Informational only — not financial advice.
            </p>
          </div>
        ) : (
          <p className="text-sm text-neutral-500">
            {holdings.length === 0
              ? "Add a holding first, then generate insights."
              : "No insights generated yet."}
          </p>
        )}
      </CardContent>
    </Card>
  );
}
